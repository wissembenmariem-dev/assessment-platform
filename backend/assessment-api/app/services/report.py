def _fallback_report(model: str, lang: str = "fr") -> dict:
    fb = _FALLBACK_BY_LANG.get((lang or "fr").lower(), _FALLBACK_BY_LANG["fr"])
    return {
        "m1_narrative": fb["msg"],
        "m2_narrative": fb["msg"],
        "m3_narrative": None,
        "m4_narrative": fb["msg"],
        "global_narrative": fb["global"],
        "interview_questions": [],
        "ai_disclaimer": _disclaimer_for(lang),
        "_model_used": model,
        "_error": fb["error"],
    }
