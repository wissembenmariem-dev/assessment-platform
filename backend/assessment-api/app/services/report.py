def build_report_prompt(
    candidate_name: str, level: str, modules: list, lang: str,
    m1: dict, m2: dict, m3: dict | None, m4: dict,
    global_score: int, global_label: str, signals: list,
) -> str:
    archetypes = {
        "architect": "L'Architecte (C élevé + O élevé)",
        "catalyst":  "Le Catalyseur (E élevé + A élevé)",
        "guardian":  "Le Gardien (C élevé + Stabilité élevée)",
        "explorer":  "L'Explorateur (O élevé + E élevé)",
        "balanced":  "Profil équilibré",
    }

    m3_section = "\nMODULE 3 — Non administré pour cette configuration.\n"
    if m3:
        m3_section = f"""
MODULE 3 — JUGEMENT SITUATIONNEL
Score : {m3['raw']} — Niveau : {m3['level']}
Style dominant : {m3.get('style', 'non déterminé')}
Par dimension :
  - Gestion des personnes : {m3['by_dim'].get('people', 0)}
  - Décision sous pression : {m3['by_dim'].get('pressure', 0)}
  - Éthique & intégrité : {m3['by_dim'].get('ethics', 0)}
  - Vision & développement : {m3['by_dim'].get('vision', 0)}
"""

    signals_text = "\n".join([
        f"  [{s['type'].upper()}] {s['label']} ({', '.join(s['modules'])}): {s['detail']}"
        for s in signals
    ]) or "  Aucun signal particulier détecté."

    lang_name = _LANG_NAMES.get((lang or "fr").lower(), "français")
    disclaimer = _disclaimer_for(lang)

    return f"""[OUTPUT LANGUAGE — STRICT]
All narrative fields (m1_narrative, m2_narrative, m3_narrative, m4_narrative,
global_narrative) and every entry in interview_questions MUST be written in
{lang_name}. The JSON keys themselves MUST stay in English exactly as specified.
The ai_disclaimer field MUST be returned verbatim as provided below — do not
translate or paraphrase it.

Génère le rapport psychométrique pour ce candidat.
Inclure dans le champ ai_disclaimer exactement ce texte : "{disclaimer}"

CANDIDAT : {candidate_name}
NIVEAU : {level}
MODULES ADMINISTRÉS : {', '.join(modules)}
LANGUE DU RAPPORT : {lang} ({lang_name})

MODULE 1 — RAISONNEMENT VERBAL ET NUMÉRIQUE
Score brut : {m1['raw']} — Niveau : {m1['level']}
Sous-scores : {m1.get('by_section', {})}

MODULE 2 — PERSONNALITÉ OCEAN
  - Ouverture (O) : {m2['O']}/40
  - Conscienciosité (C) : {m2['C']}/40
  - Extraversion (E) : {m2['E']}/40
  - Agréabilité (A) : {m2['A']}/40
  - Névrosisme (N) : {m2['N']}/40 → Stabilité : {40 - m2['N']}/40
Archétype : {archetypes.get(m2.get('archetype', 'balanced'), 'Profil équilibré')}
Désirabilité sociale détectée : {'Oui — interpréter avec prudence' if m2.get('social_desirability') else 'Non'}
{m3_section}
MODULE 4 — MOTIVATIONS ET VALEURS
Score engagement : {m4['engagement']}/50
Valeurs prioritaires : {', '.join(m4['values'].get('top3', []))}
Valeurs secondaires : {', '.join(m4['values'].get('bottom2', []))}

SCORE GLOBAL : {global_score}/100 — {global_label}

SIGNAUX INTER-MODULES :
{signals_text}

Génère le rapport en JSON strict. Les interview_questions ciblent les signaux d'attention.
Ne jamais utiliser de terme disqualificatif. Toujours contextualiser les scores faibles."""


async def generate_report(
    candidate_name: str, level: str, modules: list, lang: str,
    m1: dict, m2: dict, m3: dict | None, m4: dict,
    global_score: int, global_label: str, signals: list,
) -> dict:
    prompt = build_report_prompt(
        candidate_name=candidate_name,
        level=level,
        modules=modules,
        lang=lang,
        m1=m1, m2=m2, m3=m3, m4=m4,
        global_score=global_score,
        global_label=global_label,
        signals=signals,
    )

    model = settings.llm_report

    try:
        message = await _get_client().messages.create(
            model=model,
            max_tokens=2500,
            system=[{
                "type": "text",
                "text": REPORT_SYSTEM_PROMPT,
                "cache_control": {"type": "ephemeral"},
            }],
            messages=[{"role": "user", "content": prompt}],
        )
        raw = message.content[0].text.strip()

        if raw.startswith("```"):
            raw = raw.split("```")[1]
            if raw.startswith("json"):
                raw = raw[4:]
            raw = raw.strip()

        report = json.loads(raw)

        if "ai_disclaimer" not in report or not report["ai_disclaimer"]:
            report["ai_disclaimer"] = _disclaimer_for(lang)

        if hasattr(message, "usage"):
            usage = message.usage
            cache_read = getattr(usage, "cache_read_input_tokens", 0) or 0
            cache_created = getattr(usage, "cache_creation_input_tokens", 0) or 0
            logger.info(
                f"[report] Opus usage — input: {usage.input_tokens} | "
                f"cache_read: {cache_read} | cache_created: {cache_created} | "
                f"output: {usage.output_tokens}"
            )

        report["_model_used"] = model
        return report

    except json.JSONDecodeError as e:
        logger.error(f"[report] Erreur parsing JSON Opus : {e} | raw: {raw[:200] if 'raw' in dir() else 'N/A'}")
        _alert_report_failure(candidate_name, str(e))
        return _fallback_report(model, lang)
    except Exception as e:
        logger.error(f"[report] Erreur appel Opus : {type(e).__name__}: {e}")
        _alert_report_failure(candidate_name, str(e))
        return _fallback_report(model, lang)


def _alert_report_failure(candidate_name: str, error_detail: str) -> None:
    logger.critical(
        f"[report] ÉCHEC GÉNÉRATION RAPPORT | candidat: {candidate_name} | "
        f"erreur: {error_detail} | "
        f"action: vérifier ANTHROPIC_API_KEY et quota Anthropic"
    )


