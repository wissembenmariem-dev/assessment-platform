  let currentLang = "fr";

  function t(key, vars) {
    const dict = DICT[currentLang] || DICT.fr;
    let val = dict[key];
    if (val === undefined) {

      val = (DICT.fr && DICT.fr[key]) || key;
    }
    if (vars && typeof val === "string") {
      val = val.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? vars[name] : "{" + name + "}"));
    }
    return val;
  }

  function applyDom(root) {
    root = root || document;
    root.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    root.querySelectorAll("[data-i18n-html]").forEach((el) => {
      el.innerHTML = t(el.getAttribute("data-i18n-html"));
    });

    root.querySelectorAll("*").forEach((el) => {
      for (const attr of el.attributes) {
        const m = attr.name.match(/^data-i18n-attr-(.+)$/);
        if (m) el.setAttribute(m[1], t(attr.value));
      }
    });

    const titleEl = document.head && document.head.querySelector("title[data-i18n]");
    if (titleEl) document.title = t(titleEl.getAttribute("data-i18n"));

    document.documentElement.setAttribute("lang", currentLang);
  }

  function setLang(lang) {
    if (!DICT[lang]) lang = "fr";
    currentLang = lang;
    if (document.readyState === "loading") {
      document.addEventListener("DOMContentLoaded", applyDom.bind(null, document));
    } else {
      applyDom(document);
    }
  }

  function getLang() {
    return currentLang;
  }

  function loadStoredLang(defaultLang) {
    try {
      const stored = localStorage.getItem("assessment_ui_lang");
      if (stored && DICT[stored]) return stored;
    } catch (e) {}
    return defaultLang || "fr";
  }

  function saveLang(lang) {
    try {
      localStorage.setItem("assessment_ui_lang", lang);
    } catch (e) {}
  }

  global.K = { t, setLang, getLang, loadStoredLang, saveLang, applyDom, DICT };
